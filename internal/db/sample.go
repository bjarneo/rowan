// The sample database gives a first launch something to open. It holds a
// small shop: customers, products, orders, order items and invoices.

type sampleTable struct {
	name string
	cols []string
	rows [][]any
}

type rng struct{ a uint32 }

func (r *rng) next() float64 {
	r.a += 0x6D2B79F5
	t := r.a
	t = (t ^ t>>15) * (1 | t)
	t = (t + (t^t>>7)*(61|t)) ^ t
	return float64(t^t>>14) / 4294967296
}

func (r *rng) intn(n int) int { return int(r.next() * float64(n)) }

func pick[T any](r *rng, a []T) T { return a[r.intn(len(a))] }

var (
	firstNames = strings.Fields("Ava Liam Mia Noah Zoe Ethan Ines Kai Lena Omar Priya Sven Yuki Tomas Nora Felix Maya Jonas Aiko Diego Hana Lucas Sara Elif")
	lastNames  = strings.Fields("Novak Okafor Lindqvist Tanaka Moreau Schmidt Rossi Haddad Kowalski Silva Chen Patel Andersen Garcia Muller Kim Dubois Ivanova Nakamura Byrne")
	products   = []string{"Linen notebook", "Brass pen", "Desk lamp", "Cork board", "Walnut tray", "Canvas tote", "Steel ruler", "Felt mousepad", "Ceramic mug", "Graph pad", "Index cards", "Wool coaster", "Cable sleeve", "Phone stand", "Pencil set", "Leather folio", "Glass carafe", "Bamboo stand", "Weekly planner", "Sticky notes", "Ink refill", "Bookends", "Wall clock", "Paper clips"}
	domains    = []string{"gmail.com", "fastmail.com", "acme.io", "proton.me", "outlook.com"}
	countries  = []string{"US", "US", "DE", "GB", "FR", "NL", "SE", "JP", "CA", "BR", "ES", "NO"}
	plans      = []string{"free", "free", "starter", "starter", "team", "enterprise"}
	statuses   = []string{"paid", "paid", "paid", "shipped", "shipped", "pending", "refunded", "cancelled"}
	currencies = []string{"USD", "USD", "EUR", "EUR", "GBP"}
	planMRR    = map[string]int{"free": 0, "starter": 1900, "team": 9900, "enterprise": 49900}
)

func sampleData() []sampleTable {
	r := &rng{a: 20261102}
	base := time.Date(2025, 11, 1, 0, 0, 0, 0, time.UTC)
	stamp := func() time.Time {
		return base.Add(time.Duration(r.next() * 360 * 24 * float64(time.Hour))).Truncate(time.Second)
	}
	const nCust, nOrders, nItems = 1200, 8000, 20000

	cust := sampleTable{name: "customers", cols: []string{"id", "email", "full_name", "country", "plan", "mrr_cents", "created_at"}}
	for i := 1; i <= nCust; i++ {
		fn, ln := pick(r, firstNames), pick(r, lastNames)
		plan := pick(r, plans)
		cust.rows = append(cust.rows, []any{i, fmt.Sprintf("%s.%s%d@%s", strings.ToLower(fn), strings.ToLower(ln), i, pick(r, domains)), fn + " " + ln, pick(r, countries), plan, planMRR[plan], stamp()})
	}
	prod := sampleTable{name: "products", cols: []string{"id", "sku", "name", "price_cents", "active"}}
	for i, name := range products {
		prod.rows = append(prod.rows, []any{i + 1, fmt.Sprintf("SKU-%d", 1000+(i*379)%9000), name, (5+r.intn(90))*100 - 1, r.next() > 0.15})
	}
	orders := sampleTable{name: "orders", cols: []string{"id", "customer_id", "status", "total_cents", "currency", "placed_at", "shipped_at"}}
	placed := make([]time.Time, nOrders)
	for i := 0; i < nOrders; i++ {
		st := pick(r, statuses)
		placed[i] = stamp()
		var shipped any
		if st == "shipped" || (st == "paid" && r.next() < 0.5) {
			shipped = placed[i].Add(time.Duration(24+r.intn(96)) * time.Hour)
		}
		orders.rows = append(orders.rows, []any{10400 + i, 1 + r.intn(nCust), st, 1200 + r.intn(480)*100 - 1, pick(r, currencies), placed[i], shipped})
	}
	items := sampleTable{name: "order_items", cols: []string{"id", "order_id", "product_id", "qty", "unit_cents"}}
	for i := 1; i <= nItems; i++ {
		items.rows = append(items.rows, []any{i, 10400 + r.intn(nOrders), 1 + r.intn(len(products)), 1 + r.intn(4), (5+r.intn(90))*100 - 1})
	}
	inv := sampleTable{name: "invoices", cols: []string{"id", "order_id", "number", "issued_at", "paid_at"}}
	n := 0
	for i := 0; i < nOrders; i++ {
		if orders.rows[i][2] == "pending" || orders.rows[i][2] == "cancelled" {
			continue
		}
		n++
		issued := placed[i].Add(time.Hour)
		var paid any
		if r.next() > 0.12 {
			paid = issued.Add(time.Duration(1+r.intn(240)) * time.Hour)
		}
		inv.rows = append(inv.rows, []any{n, 10400 + i, fmt.Sprintf("INV-2026-%05d", n), issued, paid})
	}
	return []sampleTable{cust, prod, orders, items, inv}
}

func sampleDDL(engine string) []string {
	ts, id, b, txt := "timestamptz", "bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", "boolean", "text"
	switch engine {
	case "mysql":
		ts, id, b, txt = "datetime", "bigint NOT NULL AUTO_INCREMENT PRIMARY KEY", "boolean", "varchar(255)"
	case "sqlite":
		ts, id, b, txt = "text", "INTEGER PRIMARY KEY", "integer", "text"
	}
	ref := "bigint"
	if engine == "sqlite" {
		ref = "integer"
	}
	now := "now()"
	if engine == "mysql" {
		now = "CURRENT_TIMESTAMP"
	} else if engine == "sqlite" {
		now = "CURRENT_TIMESTAMP"
	}
	ddl := []string{
		`CREATE TABLE customers (
  id ` + id + `,
  email ` + txt + ` NOT NULL UNIQUE,
  full_name ` + txt + ` NOT NULL,
  country char(2) NOT NULL,
  plan ` + txt + ` NOT NULL DEFAULT 'free',
  mrr_cents integer NOT NULL DEFAULT 0,
  created_at ` + ts + ` NOT NULL DEFAULT ` + now + `
)`,
		`CREATE TABLE products (
  id ` + id + `,
  sku ` + txt + ` NOT NULL UNIQUE,
  name ` + txt + ` NOT NULL,
  price_cents integer NOT NULL,
  active ` + b + ` NOT NULL DEFAULT ` + map[bool]string{true: "1", false: "true"}[engine == "sqlite"] + `
)`,
		`CREATE TABLE orders (
  id ` + id + `,
  customer_id ` + ref + ` NOT NULL,
  status ` + txt + ` NOT NULL DEFAULT 'pending',
  total_cents integer NOT NULL,
  currency char(3) NOT NULL,
  placed_at ` + ts + ` NOT NULL DEFAULT ` + now + `,
  shipped_at ` + ts + ` NULL,
  FOREIGN KEY (customer_id) REFERENCES customers (id)
)`,
		`CREATE TABLE order_items (
  id ` + id + `,
  order_id ` + ref + ` NOT NULL,
  product_id ` + ref + ` NOT NULL,
  qty smallint NOT NULL DEFAULT 1,
  unit_cents integer NOT NULL,
  FOREIGN KEY (order_id) REFERENCES orders (id),
  FOREIGN KEY (product_id) REFERENCES products (id)
)`,
		`CREATE TABLE invoices (
  id ` + id + `,
  order_id ` + ref + ` NOT NULL,
  number ` + txt + ` NOT NULL UNIQUE,
  issued_at ` + ts + ` NOT NULL,
  paid_at ` + ts + ` NULL,
  FOREIGN KEY (order_id) REFERENCES orders (id)
)`,
		`CREATE INDEX orders_customer_id_idx ON orders (customer_id)`,
		`CREATE INDEX orders_status_idx ON orders (status)`,
		`CREATE INDEX order_items_order_id_idx ON order_items (order_id)`,
		`CREATE INDEX invoices_order_id_idx ON invoices (order_id)`,
	}
	month := map[string]string{
		"postgres": "date_trunc('month', placed_at)::date",
		"mysql":    "DATE_FORMAT(placed_at, '%Y-%m-01')",
		"sqlite":   "strftime('%Y-%m-01', placed_at)",
	}[engine]
	ddl = append(ddl, `CREATE VIEW v_monthly_revenue AS
SELECT `+month+` AS month, count(*) AS orders, sum(total_cents) / 100 AS revenue
FROM orders WHERE status IN ('paid', 'shipped')
GROUP BY 1`)
	return ddl
}

// CreateSample writes the sample schema and rows into db.
func CreateSample(ctx context.Context, db *sql.DB, engine string) error {
	for _, s := range sampleDDL(engine) {
		if _, err := db.ExecContext(ctx, s); err != nil {
			return fmt.Errorf("sample schema: %w", err)
		}
	}
	tx, err := db.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()
	for _, t := range sampleData() {
		batch := 400
		if engine == "sqlite" {
			batch = 1
		}
		for i := 0; i < len(t.rows); i += batch {
			end := min(i+batch, len(t.rows))
			var sb strings.Builder
			sb.WriteString("INSERT INTO " + t.name + " (" + strings.Join(t.cols, ", ") + ") VALUES ")
			args := make([]any, 0, (end-i)*len(t.cols))
			n := 0
			for j := i; j < end; j++ {
				if j > i {
					sb.WriteString(", ")
				}
				sb.WriteByte('(')
				for k, v := range t.rows[j] {
					if k > 0 {
						sb.WriteString(", ")
					}
					n++
					sb.WriteString(Placeholder(engine, n))
					args = append(args, sampleValue(v, engine))
				}
				sb.WriteByte(')')
			}
			if _, err := tx.ExecContext(ctx, sb.String(), args...); err != nil {
				return fmt.Errorf("sample rows in %s: %w", t.name, err)
			}
		}
		if engine == "postgres" {
			if _, err := tx.ExecContext(ctx, fmt.Sprintf("SELECT setval(pg_get_serial_sequence('%s', 'id'), (SELECT max(id) FROM %s))", t.name, t.name)); err != nil {
				return err
			}
		}
	}
	return tx.Commit()
}

func sampleValue(v any, engine string) any {
	switch x := v.(type) {
	case time.Time:
		switch engine {
		case "postgres":
			return x
		default:
			return x.Format("2006-01-02 15:04:05")
		}
	case bool:
		if engine == "sqlite" {
			if x {
				return 1
			}
			return 0
		}
	}
	return v
}

// CreateSampleFile writes the sample database to a new SQLite file.
func CreateSampleFile(ctx context.Context, path string) error {
	db, err := sql.Open("sqlite3", "file:"+path+"?_foreign_keys=1&_journal_mode=WAL")
	if err != nil {
		return err
	}
	defer db.Close()
	db.SetMaxOpenConns(1)
	return CreateSample(ctx, db, "sqlite")
}
