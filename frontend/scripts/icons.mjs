// Builds src/lib/icons.ts from Material Symbols (outlined, weight 300).
// Only the icons in NAMES are bundled. Run `npm run icons` after editing NAMES.
import { readFileSync, writeFileSync } from 'node:fs'

const NAMES = `search lock lock_open table_chart bookmark terminal receipt_long auto_awesome:star_shine database account_tree hub
swap_vert play_arrow add close check block key link chevron_right expand_more:keyboard_arrow_down light_mode dark_mode settings inbox
contrast arrow_upward arrow_downward error warning check_circle hourglass_top keyboard_return content_copy refresh
download edit delete visibility arrow_back open_in_new stop format_align_left dashboard history remove arrow_outward
call_received folder_open save tune space_dashboard view_agenda filter_alt more_horiz north_east bolt
subdirectory_arrow_right keyboard_tab radio_button_checked`.split(/\s+/).filter(Boolean)

const out = ['// Generated by scripts/icons.mjs from @material-symbols/svg-300. Do not edit.', 'export const ICONS: Record<string, string> = {']
// An entry "name:file" stores the icon under name and reads it from file.
for (const entry of NAMES) {
  const [n, file = n] = entry.split(':')
  const svg = readFileSync(`node_modules/@material-symbols/svg-300/outlined/${file}.svg`, 'utf8')
  const d = [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]).join(' ')
  out.push(`  ${n}: ${JSON.stringify(d)},`)
}
out.push('}', '')
writeFileSync('src/lib/icons.ts', out.join('\n'))
console.log(`wrote ${NAMES.length} icons`)
